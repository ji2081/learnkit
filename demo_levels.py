"""
데모 — 한 번 정의한 자료가 세 수준으로 펼쳐진다

하나의 자료는 여러 수준의 사람을 만난다.
처음 보는 사람에게 맞추면 아는 사람이 지루하고, 아는 사람에게 맞추면
처음인 사람이 첫 줄에서 멈춘다. 가운데를 잡으면 양쪽 다 놓친다.

교실에서 겪은 일이지만 교실만의 문제는 아니다 —
README도, 온보딩 문서도, 튜토리얼도 같은 자리에 선다.

그래서 자료를 여러 벌로 나누는 대신, 펼쳐지는 정도를 값으로 뺐다.

실행:  python demo_levels.py
"""
from learnkit import Learner, Lesson


# ── 정의는 한 번 ─────────────────────────────────────────────
def 공부기록(hours):
    days = ["월", "화", "수", "목", "금", "토", "일"]
    return [f"{days[i % 7]} {h}" for i, h in enumerate(hours)]


lesson = Lesson(
    title="이번 주 공부 시간",
    build=공부기록,
    branches={"이번 주": [2, 4, 1, 3, 5], "지난 주": [1, 2, 2, 4, 3]},
    hint="숫자를 네 실제 공부 시간으로 바꿔봐.",
    challenge="숫자 대신 '★'을 그 수만큼 붙여보자.",
)


# ── 펼침은 받는 쪽에 따라 ────────────────────────────────────
수준 = [
    Learner.보기부터("처음 보는 사람"),         # 결과부터, 중간 과정까지 펼쳐서
    Learner.바꿔보기("좀 해본 사람"),           # 직접 바꿔보며, 힌트와 함께
    Learner.만들어보기("더 파고들 사람"),        # 코드를 열고 도전 과제로
]


if __name__ == "__main__":
    for 수준값 in 수준:
        print(f"\n{'─' * 60}\n▶ {수준값}\n{'─' * 60}")
        lesson.render_for(수준값)

    print(f"\n{'─' * 60}")
    print(f"정의 1개  ·  펼침 {len(수준)}가지  ·  자료 제작 1회")
